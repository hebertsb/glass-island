$ErrorActionPreference = 'SilentlyContinue'
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

Add-Type -TypeDefinition @'
using System;
using System.Runtime.InteropServices;
public class GIKey {
    [DllImport("user32.dll")]
    public static extern void keybd_event(byte bVk, byte bScan, uint dwFlags, UIntPtr dwExtraInfo);
    public static void Tap(byte vk) {
        keybd_event(vk, 0, 0, UIntPtr.Zero);
        keybd_event(vk, 0, 2, UIntPtr.Zero);
    }
}
'@

$brightnessMethod = Get-WmiObject -Namespace root/WMI -Class WmiMonitorBrightnessMethods | Select-Object -First 1

# Inicializar WinRT GSMTC (funciona con Facebook, YouTube, Spotify, Chrome, Edge, VLC, etc.)
$gsmtcReady = $false
$gsmtcMgr = $null
try {
    Add-Type -AssemblyName System.Runtime.WindowsRuntime
    $asTaskGeneric = ([System.WindowsRuntimeSystemExtensions].GetMethods() | Where-Object {
        $_.Name -eq 'AsTask' -and $_.GetParameters().Count -eq 1 -and $_.GetParameters()[0].ParameterType.Name -eq 'IAsyncOperation`1'
    })[0]
    function Invoke-WinRT($WinRtTask, $ResultType) {
        $asTask = $asTaskGeneric.MakeGenericMethod($ResultType)
        $netTask = $asTask.Invoke($null, @($WinRtTask))
        $netTask.Wait(2500) | Out-Null
        return $netTask.Result
    }
    [Windows.Media.Control.GlobalSystemMediaTransportControlsSessionManager,Windows.Media.Control,ContentType=WindowsRuntime] | Out-Null
    [Windows.Media.Control.GlobalSystemMediaTransportControlsSessionMediaProperties,Windows.Media.Control,ContentType=WindowsRuntime] | Out-Null
    [Windows.Storage.Streams.IRandomAccessStreamWithContentType,Windows.Storage.Streams,ContentType=WindowsRuntime] | Out-Null
    [Windows.Storage.Streams.DataReader,Windows.Storage.Streams,ContentType=WindowsRuntime] | Out-Null
    $gsmtcMgr = Invoke-WinRT ([Windows.Media.Control.GlobalSystemMediaTransportControlsSessionManager]::RequestAsync()) ([Windows.Media.Control.GlobalSystemMediaTransportControlsSessionManager])
    if ($null -ne $gsmtcMgr) { $gsmtcReady = $true }
} catch {
    $gsmtcReady = $false
}

function Get-CurrentMediaSession {
    if (-not $gsmtcReady -or $null -eq $gsmtcMgr) { return $null }
    $sess = $gsmtcMgr.GetCurrentSession()
    if ($null -ne $sess -and $sess.SourceAppUserModelId -notmatch 'AutoGenerated|electron|glassisland') { return $sess }
    $all = $gsmtcMgr.GetSessions()
    if ($all) {
        foreach ($s in $all) {
            if ($s -and $s.SourceAppUserModelId -notmatch 'AutoGenerated|electron|glassisland') {
                return $s
            }
        }
    }
    return $null
}

$script:lastThumbKey = ''
$script:lastThumbData = ''

function Get-MediaInfoJson {
    $out = @{ title = 'Sin reproduccion activa'; artist = 'Abre YouTube, Facebook o Spotify'; source = ''; platform = ''; playing = $false; pos_sec = 0; dur_sec = 0; cover = '' }
    try {
        $sess = Get-CurrentMediaSession
        if ($null -ne $sess) {
            $props = Invoke-WinRT ($sess.TryGetMediaPropertiesAsync()) ([Windows.Media.Control.GlobalSystemMediaTransportControlsSessionMediaProperties])
            $pb = $sess.GetPlaybackInfo()
            $tl = $sess.GetTimelineProperties()
            $statusStr = if ($pb) { $pb.PlaybackStatus.ToString() } else { '' }
            $title = if ($props -and $props.Title) { $props.Title.Trim() } else { '' }
            $artist = if ($props -and $props.Artist) { $props.Artist.Trim() } else { '' }
            $appId = if ($sess.SourceAppUserModelId) { $sess.SourceAppUserModelId } else { '' }
            $src = 'Windows Media'
            $plat = 'media'
            if ($appId -match 'Spotify') { $src = 'Spotify'; $plat = 'spotify' }
            elseif ($appId -match 'cinhimbnkkaejcbeghhkhk|YouTubeMusic') { $src = 'YouTube Music'; $plat = 'youtube-music' }
            elseif ($appId -match 'agimnkijcaahngcdmfeangaknmldooml|YouTube') { $src = 'YouTube'; $plat = 'youtube' }
            elseif ($appId -match 'chrome') { $src = 'Chrome'; $plat = 'chrome' }
            elseif ($appId -match 'msedge|Edge') { $src = 'Edge'; $plat = 'edge' }
            elseif ($appId -match 'brave') { $src = 'Brave'; $plat = 'chrome' }
            elseif ($appId -match 'firefox') { $src = 'Firefox'; $plat = 'media' }
            elseif ($appId) { $src = ($appId -replace '\.exe$', '').Split('!')[-1] }

            # Si viene de Chrome/Edge, revisa si la ventana activa de reproducción es YouTube o YouTube Music
            if ($plat -eq 'chrome' -or $plat -eq 'edge') {
                $ytWin = Get-Process -Name chrome,msedge -ErrorAction SilentlyContinue | Where-Object { $_.MainWindowTitle -match 'YouTube Music| - YouTube' } | Select-Object -First 1
                if ($ytWin) {
                    if ($ytWin.MainWindowTitle -match 'YouTube Music') { $src = 'YouTube Music'; $plat = 'youtube-music' }
                    else { $src = 'YouTube'; $plat = 'youtube' }
                } elseif ($title -match 'Facebook') {
                    $src = 'Facebook'; $plat = 'facebook'
                }
            }

            if ($title) {
                $out.title = $title
                $out.artist = if ($artist) { $artist } else { $src }
                $out.source = $src
                $out.platform = $plat
                $out.playing = ($statusStr -eq 'Playing')
                if ($tl) {
                    $startSec = [double]$tl.StartTime.TotalSeconds
                    $endSec = [double]$tl.EndTime.TotalSeconds
                    $rawPos = [double]$tl.Position.TotalSeconds
                    $dur = [math]::Max(0, $endSec - $startSec)
                    $pos = [math]::Max(0, $rawPos - $startSec)
                    if ($out.playing -and $tl.LastUpdatedTime.Year -gt 2000) {
                        $elapsedSince = ([DateTimeOffset]::UtcNow - $tl.LastUpdatedTime).TotalSeconds
                        if ($elapsedSince -gt 0 -and $elapsedSince -lt 300) {
                            $pos = $pos + $elapsedSince
                        }
                    }
                    if ($dur -gt 0 -and $dur -le 43200) {
                        $out.pos_sec = [int][math]::Min($dur, [math]::Max(0, $pos))
                        $out.dur_sec = [int]$dur
                    }
                }
                # Captura la carátula real del video/canción (YouTube, Spotify, etc.) cacheada por título
                $thumbKey = "$title|$artist"
                if ($thumbKey -eq $script:lastThumbKey -and $script:lastThumbData) {
                    $out.cover = $script:lastThumbData
                } elseif ($props -and $props.Thumbnail) {
                    try {
                        $stream = Invoke-WinRT ($props.Thumbnail.OpenReadAsync()) ([Windows.Storage.Streams.IRandomAccessStreamWithContentType])
                        if ($null -ne $stream -and $stream.Size -gt 0 -and $stream.Size -lt 600000) {
                            $size = [uint32]$stream.Size
                            $reader = [Windows.Storage.Streams.DataReader]::new($stream.GetInputStreamAt(0))
                            $loadOp = $reader.LoadAsync($size)
                            $asTaskUInt = ([System.WindowsRuntimeSystemExtensions].GetMethods() | Where-Object {
                                $_.Name -eq 'AsTask' -and $_.GetParameters().Count -eq 1 -and $_.GetParameters()[0].ParameterType.Name -eq 'IAsyncOperation`1'
                            })[0].MakeGenericMethod([uint32])
                            $tLoad = $asTaskUInt.Invoke($null, @($loadOp))
                            $tLoad.Wait(1200) | Out-Null
                            $bytes = New-Object byte[] $size
                            $reader.ReadBytes($bytes)
                            $mime = if ($stream.ContentType) { $stream.ContentType } else { 'image/jpeg' }
                            $b64 = "data:$mime;base64," + [Convert]::ToBase64String($bytes)
                            $script:lastThumbKey = $thumbKey
                            $script:lastThumbData = $b64
                            $out.cover = $b64
                            $reader.Dispose()
                            $stream.Dispose()
                        }
                    } catch {}
                }
            }
        }
    } catch {}
    return ($out | ConvertTo-Json -Compress)
}

function Invoke-MediaAction([string]$action) {
    $ok = $false
    try {
        $sess = Get-CurrentMediaSession
        if ($action -eq 'play_pause') {
            if ($null -ne $sess) {
                $res = Invoke-WinRT ($sess.TryTogglePlayPauseAsync()) ([bool])
                $ok = [bool]$res
            }
            if (-not $ok) { [GIKey]::Tap(0xB3); $ok = $true }
        } elseif ($action -eq 'next') {
            if ($null -ne $sess) {
                $res = Invoke-WinRT ($sess.TrySkipNextAsync()) ([bool])
                $ok = [bool]$res
            }
            if (-not $ok) { [GIKey]::Tap(0xB0); $ok = $true }
        } elseif ($action -eq 'prev') {
            if ($null -ne $sess) {
                $res = Invoke-WinRT ($sess.TrySkipPreviousAsync()) ([bool])
                $ok = [bool]$res
            }
            if (-not $ok) { [GIKey]::Tap(0xB1); $ok = $true }
        } elseif ($action -eq 'vol_up') {
            [GIKey]::Tap(0xAF); $ok = $true
        } elseif ($action -eq 'vol_down') {
            [GIKey]::Tap(0xAE); $ok = $true
        } elseif ($action -eq 'vol_mute') {
            [GIKey]::Tap(0xAD); $ok = $true
        }
    } catch {}
    return (@{ ok = $ok; action = $action } | ConvertTo-Json -Compress)
}

function Get-ExtraTelemetryJson {
    $b = Get-CimInstance Win32_Battery | Select-Object -First 1
    $d = Get-PSDrive C
    $br = (Get-WmiObject -Namespace root/WMI -Class WmiMonitorBrightness | Select-Object -First 1).CurrentBrightness
    $out = @{
        battery_percent = if ($b) { [int]$b.EstimatedChargeRemaining } else { 100 }
        battery_plugged = if ($b) { ($b.BatteryStatus -eq 2) } else { $true }
        disk_c_free_gb = [math]::Round($d.Free / 1GB, 1)
        disk_c_percent = [math]::Round(($d.Used / ($d.Used + $d.Free)) * 100, 1)
        brightness = if ($null -ne $br) { [int]$br } else { 80 }
    }
    return ($out | ConvertTo-Json -Compress)
}

[Console]::Out.WriteLine('{"ready":true,"gsmtc":' + ($gsmtcReady.ToString().ToLower()) + '}')
[Console]::Out.Flush()

while ($null -ne ($line = [Console]::In.ReadLine())) {
    if (-not $line.Trim()) { continue }
    try {
        $req = $line | ConvertFrom-Json
        $id = $req.id
        $cmd = $req.cmd
        $payload = '{}'
        if ($cmd -eq 'media_info') {
            $payload = Get-MediaInfoJson
        } elseif ($cmd -eq 'media') {
            $payload = Invoke-MediaAction ([string]$req.action)
        } elseif ($cmd -eq 'brightness') {
            $lvl = [math]::Max(5, [math]::Min(100, [int]$req.level))
            if ($null -eq $brightnessMethod) {
                $brightnessMethod = Get-WmiObject -Namespace root/WMI -Class WmiMonitorBrightnessMethods | Select-Object -First 1
            }
            if ($null -ne $brightnessMethod) {
                $brightnessMethod.WmiSetBrightness(0, $lvl) | Out-Null
                $payload = (@{ ok = $true; brightness = $lvl } | ConvertTo-Json -Compress)
            } else {
                $payload = '{"ok":false}'
            }
        } elseif ($cmd -eq 'extra') {
            $payload = Get-ExtraTelemetryJson
        } elseif ($cmd -eq 'quit') {
            break
        }
        [Console]::Out.WriteLine('{"id":' + $id + ',"data":' + $payload + '}')
        [Console]::Out.Flush()
    } catch {
        [Console]::Out.WriteLine('{"id":0,"error":"parse"}')
        [Console]::Out.Flush()
    }
}
